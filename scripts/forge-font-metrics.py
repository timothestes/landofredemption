#!/usr/bin/env python3
"""Generate app/forge/lib/fontMetrics.ts: advance widths of the Forge preview's body faces
(Arimo Bold for abilities, Arimo Italic for scripture) so the preview can wrap text the way
the browser will and tell whether an ability fits its printed box, plus the title face
(Symphony Black, the licensed TTF in gitignored tmp/) so the title is squeezed only when it
really overruns its frame. Only advance widths leave the licensed file. Stdlib only.

    make forge-font-metrics   (= python3.11 scripts/forge-font-metrics.py --title tmp/SYMPHOBL.TTF)
"""
import argparse
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = {"bold": "Arimo-Bold.ttf", "italic": "Arimo-Italic.ttf"}
# ASCII printable plus the punctuation card text actually uses.
CHARS = [chr(c) for c in range(32, 127)] + list("‘’“”–—… é")


def tables(b):
    n = struct.unpack(">H", b[4:6])[0]
    return {b[12 + 16 * i:16 + 16 * i].decode(): struct.unpack(">II", b[20 + 16 * i:28 + 16 * i]) for i in range(n)}


def cmap4(b, off):
    ntab = struct.unpack(">H", b[off + 2:off + 4])[0]
    for i in range(ntab):
        sub = off + struct.unpack(">HHI", b[off + 4 + 8 * i:off + 12 + 8 * i])[2]
        if struct.unpack(">H", b[sub:sub + 2])[0] != 4:
            continue
        segx2 = struct.unpack(">H", b[sub + 6:sub + 8])[0]
        seg = segx2 // 2
        ends = struct.unpack(f">{seg}H", b[sub + 14:sub + 14 + segx2])
        p = sub + 16 + segx2
        starts = struct.unpack(f">{seg}H", b[p:p + segx2]); p += segx2
        deltas = struct.unpack(f">{seg}h", b[p:p + segx2]); p += segx2
        ros = p
        ro = struct.unpack(f">{seg}H", b[p:p + segx2])
        m = {}
        for s in range(seg):
            for c in range(starts[s], min(ends[s], 0xFFFE) + 1):
                if ro[s] == 0:
                    g = (c + deltas[s]) & 0xFFFF
                else:
                    gi = ros + 2 * s + ro[s] + 2 * (c - starts[s])
                    g = struct.unpack(">H", b[gi:gi + 2])[0]
                    if g:
                        g = (g + deltas[s]) & 0xFFFF
                if g:
                    m[chr(c)] = g
        return m
    raise SystemExit("no format-4 cmap")


def advances(path, only_mapped=False):
    """(units per em, {char: advance}); with `only_mapped`, characters the font has no glyph
    for are left out so the consumer falls back instead of using .notdef's width."""
    b = path.read_bytes()
    t = tables(b)
    upem = struct.unpack(">H", b[t["head"][0] + 18:t["head"][0] + 20])[0]
    nhm = struct.unpack(">H", b[t["hhea"][0] + 34:t["hhea"][0] + 36])[0]
    hm = t["hmtx"][0]
    cm = cmap4(b, t["cmap"][0])

    def adv(ch):
        g = min(cm.get(ch, 0), nhm - 1)
        return struct.unpack(">H", b[hm + 4 * g:hm + 4 * g + 2])[0]

    return upem, {ch: adv(ch) for ch in CHARS if not only_mapped or ch in cm}


def table_line(key, upem, adv):
    scaled = {ch: round(w * 1000 / upem) for ch, w in adv.items()}
    entries = ", ".join(f"[{json.dumps(ch, ensure_ascii=False)}, {w}]" for ch, w in scaled.items())
    return f"export const {key}_ADVANCES: ReadonlyMap<string, number> = new Map([{entries}]);"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", default=str(ROOT / "tmp/SYMPHOBL.TTF"),
                    help="the licensed title face (Symphony Black); never committed")
    args = ap.parse_args()
    title = Path(args.title)
    if not title.is_file():
        raise SystemExit(f"title face not found: {title} (see `make forge-fonts`)")
    out = ["// GENERATED by scripts/forge-font-metrics.py from public/forge/fonts and the title face",
           "// in tmp/ — do not edit. Advance widths in font units (1000 per em): the body faces let",
           "// textFit.ts wrap abilities and scripture the way the browser will; the title face",
           "// (Symphony Black — only its widths are here, never the font) tells CardSvg whether a",
           "// name overruns its frame and has to be squeezed.", "",
           "export const FONT_UPEM = 1000;", ""]
    for key, file in FONTS.items():
        out.append(table_line(key.upper(), *advances(ROOT / "public/forge/fonts" / file)))
        out.append("")
    out.append(table_line("TITLE", *advances(title, only_mapped=True)))
    out.append("")
    (ROOT / "app/forge/lib/fontMetrics.ts").write_text("\n".join(out), encoding="utf-8")
    print("wrote app/forge/lib/fontMetrics.ts")


if __name__ == "__main__":
    main()
